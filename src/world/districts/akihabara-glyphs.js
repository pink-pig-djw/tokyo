/** Greedy rectangles covering the '#' cells of a bitmap: [col, row, w, h] (row 0 = top). */
function rects(rows) {
  const H = rows.length, W = rows[0].length;
  const done = rows.map((r) => [...r].map((c) => c !== '#'));
  const out = [];
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (done[y][x]) continue;
      let w = 1;
      while (x + w < W && !done[y][x + w]) w++;
      let h = 1;
      while (y + h < H) {
        let ok = true;
        for (let k = 0; k < w; k++) if (done[y + h][x + k]) { ok = false; break; }
        if (!ok) break;
        h++;
      }
      for (let yy = y; yy < y + h; yy++) for (let k = 0; k < w; k++) done[yy][x + k] = true;
      out.push([x, y, w, h]);
    }
  }
  return out;
}

const CACHE = new Map();
function glyph(ch) {
  if (!CACHE.has(ch)) {
    const g = G[ch] || G[' '];
    CACHE.set(ch, { w: g[0].length, h: g.length, r: rects(g) });
  }
  return CACHE.get(ch);
}

/** Width in metres of `str` drawn with glyph height `h` (kanji/kana cells are square). */
export function textWidth(str, h, gap = 0.18) {
  let w = 0;
  for (const ch of str) {
    const g = glyph(ch);
    const px = h / g.h;
    w += g.w * px + gap * h;
  }
  return Math.max(0, w - gap * h);
}

/**
 * Lettering on a vertical plane facing compass `bearing`: the string is centred on (x, z),
 * its bottom at y, glyphs `h` metres tall; `off` = distance in front of the wall.
 */
export function text(kit, str, x, y, z, bearing, h, color, style, off = 0.4, gap = 0.18) {
  const b = (bearing * Math.PI) / 180;
  const nx = Math.sin(b), nz = -Math.cos(b);
  const tx = -Math.cos(b), tz = -Math.sin(b);          // right-hand direction seen from the front
  const W = textWidth(str, h, gap);
  let u = -W / 2;
  const cx = x + nx * off, cz = z + nz * off;
  for (const ch of str) {
    const g = glyph(ch);
    const px = h / g.h;
    for (const [c, r, w, hh] of g.r) {
      const u0 = u + c * px, u1 = u0 + w * px;
      const y1 = y + h - r * px, y0 = y1 - hh * px;
      kit.quad([cx + tx * u0, y0, cz + tz * u0], [cx + tx * u1, y0, cz + tz * u1],
        [cx + tx * u1, y1, cz + tz * u1], [cx + tx * u0, y1, cz + tz * u0], color, style);
    }
    u += g.w * px + gap * h;
  }
  return W;
}

/** Vertical (top-to-bottom) lettering, e.g. on a blade sign; (x, z) = column centre, y = top. */
export function textV(kit, str, x, y, z, bearing, h, color, style, off = 0.4, gap = 0.12) {
  let yy = y;
  for (const ch of str) {
    const g = glyph(ch);
    const hh = h * g.h / Math.max(g.h, g.w);
    yy -= hh;
    text(kit, ch, x, yy, z, bearing, hh, color, style, off, 0);
    yy -= gap * h;
  }
  return y - yy;
}
